-- Least privilege. All entitlement writes belong to admins or trusted services.
CREATE FUNCTION public.is_admin() RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
 SELECT EXISTS (SELECT FROM public.profiles WHERE id=auth.uid() AND role='admin');
$$;
CREATE FUNCTION public.has_active_subscription() RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
 SELECT EXISTS (SELECT FROM public.subscriptions WHERE user_id=auth.uid() AND status='active'
 AND (current_period_end > now() OR (plan='comp' AND current_period_end IS NULL)));
$$;
CREATE FUNCTION public.can_read_tier(tier text) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
 SELECT tier='production' OR EXISTS (SELECT FROM public.profiles WHERE id=auth.uid()
 AND (access_tier='test' OR (access_tier='stage' AND tier='stage')));
$$;
CREATE FUNCTION public.can_read_content(tier text, premium boolean) RETURNS boolean LANGUAGE sql STABLE SET search_path = '' AS $$
 SELECT public.is_admin() OR (public.can_read_tier(tier) AND (premium IS FALSE OR public.has_active_subscription()));
$$;
-- Users may update only harmless profile fields. Trigger also protects upserts.
CREATE FUNCTION public.guard_profile_entitlements() RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
 IF current_user IN ('anon','authenticated') AND NOT public.is_admin() THEN
  IF TG_OP='INSERT' THEN
   IF NEW.role <> 'viewer' OR NEW.is_admin OR NEW.access_tier <> 'production' THEN
    RAISE EXCEPTION 'Profile entitlements are server-managed' USING ERRCODE='42501';
   END IF;
  ELSIF NEW.role IS DISTINCT FROM OLD.role OR NEW.is_admin IS DISTINCT FROM OLD.is_admin
     OR NEW.access_tier IS DISTINCT FROM OLD.access_tier OR NEW.id IS DISTINCT FROM OLD.id THEN
   RAISE EXCEPTION 'Profile entitlements are server-managed' USING ERRCODE='42501';
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER protect_profile_entitlements BEFORE INSERT OR UPDATE ON public.profiles FOR EACH ROW EXECUTE FUNCTION public.guard_profile_entitlements();
CREATE FUNCTION public.handle_new_user() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
 INSERT INTO public.profiles(id,email,full_name) VALUES(NEW.id,NEW.email,NEW.raw_user_meta_data->>'full_name');
 RETURN NEW;
END $$;
CREATE TRIGGER on_auth_user_created AFTER INSERT ON auth.users FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();
