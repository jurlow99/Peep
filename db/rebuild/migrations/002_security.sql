GRANT SELECT ON public.movies TO authenticated, service_role;
-- View counters are intentionally service-only until rate-limited tracking exists.
CREATE FUNCTION public.increment_view(p_id text, p_table text) RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
 IF p_table NOT IN ('videos','episodes') THEN RAISE EXCEPTION 'Unsupported content table'; END IF;
 EXECUTE format('UPDATE public.%I SET views=views+1 WHERE id::text=$1',p_table) USING p_id;
END $$;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA public FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.is_admin(), public.has_active_subscription(), public.can_read_tier(text), public.can_read_content(text,boolean) TO anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.increment_view(text,text) TO service_role;
